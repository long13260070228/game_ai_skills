#!/usr/bin/env python3
"""Package a curated review directory as one offline evidence ZIP and render its download entry."""
import argparse
import hashlib
from html.parser import HTMLParser
import json
import os
from pathlib import Path
import tempfile
from urllib.parse import unquote, urlsplit
import zipfile
import report

EXCLUDED_DIRS={'packages','cache','.git','__pycache__'}
EXCLUDED_FILES={'delivery.json','package-validation.json','MANIFEST.json','MANIFEST.sha256'}

def digest(data):
    return hashlib.sha256(data).hexdigest()

def digest_file(path):
    value=hashlib.sha256()
    with Path(path).open('rb') as handle:
        for chunk in iter(lambda:handle.read(1024*1024),b''):
            value.update(chunk)
    return value.hexdigest()

def source_files(root):
    files={}
    def scan_error(error):
        raise error
    for current,dirs,names in os.walk(root,topdown=True,followlinks=False,onerror=scan_error):
        dirs[:]=sorted(name for name in dirs if name not in EXCLUDED_DIRS and not name.endswith('.pyc'))
        for name in dirs+sorted(names):
            if name in EXCLUDED_DIRS or name.endswith('.pyc'):
                continue
            path=Path(current)/name
            relative=path.relative_to(root)
            if path.is_symlink():
                raise ValueError('Resolve and curate symlink evidence before packaging: '+str(relative))
            if path.is_file() and not (len(relative.parts)==1 and path.name in EXCLUDED_FILES):
                files[relative.as_posix()]=path
    return dict(sorted(files.items()))

def verify_archive(path,manifest):
    expected=[item['path'] for item in manifest]+['MANIFEST.json']
    if len(expected)!=len(set(expected)):
        raise ValueError('Duplicate manifest path')
    with zipfile.ZipFile(path) as archive:
        names=archive.namelist()
        if len(names)!=len(set(names)) or set(names)!=set(expected):
            raise ValueError('Archive entries do not match manifest')
        try:
            actual_manifest=json.loads(archive.read('MANIFEST.json'))
        except (UnicodeDecodeError,json.JSONDecodeError) as exc:
            raise ValueError('Invalid archive manifest') from exc
        if actual_manifest!=manifest:
            raise ValueError('Archive manifest content mismatch')
        for item in manifest:
            length=0;value=hashlib.sha256()
            with archive.open(item['path']) as source:
                for chunk in iter(lambda:source.read(1024*1024),b''):
                    length+=len(chunk);value.update(chunk)
            if length!=item['bytes'] or value.hexdigest()!=item['sha256']:
                raise ValueError('Manifest mismatch: '+item['path'])
    return True

def build_archive(root,destination,overrides,source_inventory=None):
    root=root.resolve();destination=destination.resolve()
    if destination.is_relative_to(root):
        raise ValueError('ZIP must be outside the report directory')
    sources=source_files(root) if source_inventory is None else dict(source_inventory)
    for name,path in sources.items():
        relative=Path(name)
        source=Path(path)
        if relative.is_absolute() or '..' in relative.parts or name=='MANIFEST.json':
            raise ValueError('Unsafe source inventory path: '+name)
        if source.is_symlink() or not source.is_file() or not source.resolve().is_relative_to(root):
            raise ValueError('Source inventory must contain regular files under report directory: '+name)
    files=dict(sources)
    for name,data in overrides.items():
        if Path(name).is_absolute() or '..' in Path(name).parts:
            raise ValueError('Unsafe override path')
        if name=='MANIFEST.json':
            raise ValueError('MANIFEST.json is generated by the packager')
        files[name]=data
    destination.parent.mkdir(parents=True,exist_ok=True)
    handle,tmp=tempfile.mkstemp(prefix='.evidence-',suffix='.zip',dir=destination.parent)
    os.close(handle)
    try:
        with zipfile.ZipFile(tmp,'w',zipfile.ZIP_DEFLATED) as archive:
            manifest=[]
            for name in sorted(files):
                value=hashlib.sha256();length=0
                if name in overrides:
                    data=overrides[name]
                    if not isinstance(data,bytes):
                        raise TypeError('Archive overrides must be bytes: '+name)
                    value.update(data);length=len(data);archive.writestr(name,data)
                else:
                    with Path(files[name]).open('rb') as source,archive.open(name,'w',force_zip64=True) as output:
                        for chunk in iter(lambda:source.read(1024*1024),b''):
                            length+=len(chunk);value.update(chunk);output.write(chunk)
                manifest.append({'path':name,'bytes':length,'sha256':value.hexdigest()})
            manifest_bytes=(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n').encode()
            archive.writestr('MANIFEST.json',manifest_bytes)
        verify_archive(tmp,manifest)
        os.replace(tmp,destination)
    finally:
        if Path(tmp).exists():Path(tmp).unlink()
    return {'name':destination.name,'bytes':destination.stat().st_size,'sha256':digest_file(destination),'files':len(manifest)}

class Links(HTMLParser):
    def __init__(self):
        super().__init__();self.hrefs=[];self.ids=set()
    def handle_starttag(self,tag,attrs):
        attrs=dict(attrs)
        if 'id' in attrs:self.ids.add(attrs['id'])
        for attr in ('href','src','poster'):
            if attrs.get(attr):self.hrefs.append(attrs[attr])

def check_links(root,markup,included=None,allowed_external=()):
    root=root.resolve();allowed_external={p.resolve() for p in allowed_external}
    parser=Links();parser.feed(markup);errors=[];fragment_ids={}
    for href in parser.hrefs:
        url=urlsplit(href)
        if url.scheme in ('http','https','mailto','data'):continue
        if url.scheme or url.netloc:errors.append(href);continue
        if not url.path:
            if url.fragment and unquote(url.fragment) not in parser.ids:errors.append(href)
            continue
        path=(root/unquote(url.path)).resolve()
        if path.is_relative_to(root):
            if not path.is_file() or (included is not None and path.relative_to(root).as_posix() not in included):
                errors.append(href);continue
        elif path not in allowed_external or not path.is_file():
            errors.append(href);continue
        if url.fragment and path.suffix.lower() in ('.html','.htm'):
            if path not in fragment_ids:
                linked=Links();linked.feed(path.read_text());fragment_ids[path]=linked.ids
            if unquote(url.fragment) not in fragment_ids[path]:errors.append(href)
    if errors:raise ValueError('Missing or unpackaged report links: '+', '.join(sorted(set(errors))))
    return len(parser.hrefs)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory',type=Path,help='Curated report, evidence, inputs and audit; exclude whole-repository caches before calling')
    parser.add_argument('--zip',required=True,type=Path,help='Output ZIP outside directory')
    parser.add_argument('--basename',default='review')
    parser.add_argument('--finalize',action='store_true',help='Generate Markdown from the frozen JSON before packaging')
    args=parser.parse_args();root=args.directory.resolve()
    if Path(args.basename).name!=args.basename or args.basename in ('.','..'):parser.error('Invalid basename')
    doc=json.loads((root/(args.basename+'.json')).read_text())
    errors=report.validate(doc)
    if errors:raise SystemExit('\n'.join(errors))
    if not (root/'data-sources.md').is_file():raise SystemExit('Missing required report: data-sources.md')
    if args.finalize:
        (root/(args.basename+'.md')).write_text(report.markdown(doc))
    elif not (root/(args.basename+'.md')).is_file():
        raise SystemExit('Missing required report: '+args.basename+'.md')
    notice=doc.get('presentation_revision',{}).get('notice','')
    package=report.render(doc,args.basename,{'profile':'package','notice':notice})
    inventory=source_files(root)
    link_count=check_links(root,package,included=set(inventory))
    meta=build_archive(root,args.zip,{'index.html':package.encode()},source_inventory=inventory)
    checksum=args.zip.resolve().with_name(args.zip.stem+'-SHA256.txt')
    checksum.write_text(meta['sha256']+'  '+args.zip.name+'\n')
    context={**meta,'profile':'local','url':os.path.relpath(args.zip.resolve(),root),'checksum_url':os.path.relpath(checksum,root),'notice':notice}
    local=report.render(doc,args.basename,context)
    check_links(root,local,allowed_external=(args.zip,checksum))
    (root/'delivery.json').write_text(json.dumps(context,ensure_ascii=False,indent=2)+'\n')
    (root/'index.html').write_text(local)
    print(json.dumps({**meta,'zip':str(args.zip.resolve()),'checksum':str(checksum),'checked_package_links':link_count},ensure_ascii=False))

if __name__=='__main__':main()
